    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int row = bookTable.getSelectedRow();
        if(row == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Select a row to edit");
            return;
        }
        txtBookName.setText(bookTable.getValueAt(row, 1).toString());
        cmbCategory.setSelectedItem(bookTable.getValueAt(row, 2).toString());
        cmbAuthor.setSelectedItem(bookTable.getValueAt(row, 3).toString());
        cmbPublisher.setSelectedItem(bookTable.getValueAt(row, 4).toString());
        txtContents.setText(bookTable.getValueAt(row, 5).toString());
        txtPages.setText(bookTable.getValueAt(row, 6).toString());
        txtEdition.setText(bookTable.getValueAt(row, 7).toString());

        // TODO add your handling code here:
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        int row = bookTable.getSelectedRow();
        if(row == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Select a row to delete");
            return;
        }
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) bookTable.getModel();
        model.removeRow(row);

        // TODO add your handling code here:
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed

        String name = txtBookName.getText();
        String category = cmbCategory.getSelectedItem().toString();
        String author = cmbAuthor.getSelectedItem().toString();
        String publisher = cmbPublisher.getSelectedItem().toString();
        String contents = txtContents.getText();
        String pages = txtPages.getText();
        String edition = txtEdition.getText();

        // Check if empty
        if(name.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter Book Title");
            return;
        }
        // Add to table
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) bookTable.getModel();
        model.addRow(new Object[]{model.getRowCount()+1, name, category, author, publisher, contents, pages, edition});

        // Clear after add
        txtBookName.setText("");
        txtContents.setText("");
        txtPages.setText("");
        txtEdition.setText("");

        // TODO add your handling code here:
    }//GEN-LAST:event_btnAddActionPerformed

